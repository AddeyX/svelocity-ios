import { nativeBindings } from './bindings.js';
import type { Argument, ComponentIR, Expression, TextPart, ViewNode } from './types.js';

// Prefix source names to avoid Swift keywords, View members, and @State backing names.
export const swiftIdentifier = (name: string): string => `sv_${name}`;

export function swiftString(value: string): string {
  let result = '"';
  for (const char of value) {
    const code = char.codePointAt(0)!;
    if (char === '"' || char === '\\') result += `\\${char}`;
    else if (char === '\n') result += '\\n';
    else if (char === '\r') result += '\\r';
    else if (char === '\t') result += '\\t';
    else if (code >= 0xd800 && code <= 0xdfff) throw new Error('Unpaired surrogate in Swift string.');
    else if (code < 32 || code === 127) result += `\\u{${code.toString(16)}}`;
    else result += char;
  }
  return result + '"';
}

function expression(value: Expression): string {
  switch (value.kind) {
    case 'literal': return typeof value.value === 'string' ? swiftString(value.value) : String(value.value);
    case 'reference': return swiftIdentifier(value.name);
    case 'not': return `!(${expression(value.operand)})`;
  }
}

function text(parts: TextPart[]): string {
  // Escape source strings before inserting Swift interpolation, preventing injection.
  return '"' + parts.map(part => part.kind === 'text'
    ? swiftString(part.value).slice(1, -1)
    : `\\(${expression(part.value)})`).join('') + '"';
}

function argument(value: Argument): string {
  if (value.kind === 'number') return String(value.value);
  return `{ ${value.assignments.map(item => `${swiftIdentifier(item.name)} = ${expression(item.value)}`).join('; ')} }`;
}

function nodes(body: ViewNode[], level: number): string[] {
  const indent = '    '.repeat(level);
  const lines: string[] = [];
  for (const node of body) {
    if (node.kind === 'if') {
      lines.push(`${indent}if ${expression(node.condition)} {`, ...nodes(node.consequent, level + 1));
      if (node.alternate !== null) lines.push(`${indent}} else {`, ...nodes(node.alternate, level + 1));
      lines.push(`${indent}}`);
      continue;
    }
    const binding = nativeBindings[node.binding]!;
    const args = node.arguments.filter(a => binding.properties[a.name]!.placement === 'initializer')
      .map(a => `${binding.properties[a.name]!.swiftName}: ${argument(a)}`);
    if (binding.content === 'text') args.unshift(`verbatim: ${text(node.text)}`);
    let call = `${binding.swiftName}(${args.join(', ')})`;
    if (binding.content === 'views' || binding.content === 'label') {
      // Swift permits empty argument parentheses before a trailing closure.
      lines.push(`${indent}${call} {`);
      lines.push(...(binding.content === 'views'
        ? nodes(node.children, level + 1)
        : [`${indent}    SwiftUI.Text(verbatim: ${text(node.text)})`]));
      lines.push(`${indent}}`);
    } else lines.push(`${indent}${call}`);
    for (const value of node.arguments) {
      const definition = binding.properties[value.name]!;
      if (definition.placement === 'modifier') lines.push(`${indent}    .${definition.swiftName}(${argument(value)})`);
    }
  }
  return lines;
}

export function emitSwift(component: ComponentIR): string {
  const lines = ['// Generated by Svelocity. Do not edit.', 'import SwiftUI', '', `struct ${component.name}: SwiftUI.View {`];
  for (const declaration of component.declarations) {
    const storage = declaration.state ? '@SwiftUI.State private var' : 'private let';
    const type = declaration.valueType === 'string' ? 'Swift.String' : 'Swift.Bool';
    const initial = typeof declaration.initial === 'string' ? swiftString(declaration.initial) : String(declaration.initial);
    lines.push(`    ${storage} ${swiftIdentifier(declaration.name)}: ${type} = ${initial}`);
  }
  if (component.declarations.length > 0) lines.push('');
  lines.push('    @SwiftUI.ViewBuilder', '    var body: some SwiftUI.View {', ...nodes(component.body, 2), '    }', '}', '');
  return lines.join('\n');
}
